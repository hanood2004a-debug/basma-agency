const originalText = new WeakMap();
const originalAttrs = new WeakMap();

function translateLiteralContent(lang) {
  const dict = literalTranslations[lang] || {};
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    const parent = node.parentElement;
    if (!parent || parent.closest('script,style,[data-i18n]')) continue;
    if (!originalText.has(node)) originalText.set(node, node.nodeValue);
    const source = originalText.get(node);
    const trimmed = source.trim();
    if (!trimmed) continue;
    if (lang === 'ar') {
      node.nodeValue = source;
    } else if (dict[trimmed]) {
      node.nodeValue = source.replace(trimmed, dict[trimmed]);
    }
  }
  document.querySelectorAll('[placeholder],option').forEach(function(el) {
    if (!originalAttrs.has(el)) originalAttrs.set(el, { placeholder: el.getAttribute('placeholder'), text: el.textContent });
    const saved = originalAttrs.get(el);
    if (lang === 'ar') {
      if (saved.placeholder !== null) el.setAttribute('placeholder', saved.placeholder);
      if (el.tagName === 'OPTION') el.textContent = saved.text;
    } else {
      if (saved.placeholder && dict[saved.placeholder]) el.setAttribute('placeholder', dict[saved.placeholder]);
      if (el.tagName === 'OPTION' && dict[saved.text.trim()]) el.textContent = dict[saved.text.trim()];
    }
  });
}

const langDirection = { ar:"rtl", en:"ltr", es:"ltr" };
const langLabel = { ar:"AR", en:"EN", es:"ES" };

function setLang(lang) {
  if (!['ar','en','es'].includes(lang)) lang = 'ar';
  document.querySelectorAll('[data-lang-current]').forEach(function(el){ el.textContent = langLabel[lang] || 'AR'; });
  if (lang === 'ar') {
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      if (el.hasAttribute('data-i18n-ar')) el.textContent = el.getAttribute('data-i18n-ar');
    });
    translateLiteralContent('ar');
    document.documentElement.setAttribute('lang', 'ar');
    document.documentElement.setAttribute('dir', 'rtl');
    localStorage.setItem('basma_lang', 'ar');
    syncInternalLinks('ar');
    return;
  }
  const dict = translations[lang];
  if (!dict) return;
  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    if (!el.hasAttribute('data-i18n-ar')) el.setAttribute('data-i18n-ar', el.textContent);
    const key = el.getAttribute('data-i18n');
    if (dict[key]) el.textContent = dict[key];
  });
  translateLiteralContent(lang);
  document.documentElement.setAttribute('lang', lang);
  document.documentElement.setAttribute('dir', langDirection[lang] || 'ltr');
  localStorage.setItem('basma_lang', lang);
  syncInternalLinks(lang);
}

function syncInternalLinks(lang) {
  document.querySelectorAll('a[href]').forEach(function(link) {
    const raw = link.getAttribute('href');
    if (!raw || raw.startsWith('#') || raw.includes('{{') || /^(mailto:|tel:|javascript:)/i.test(raw)) return;
    try {
      const url = new URL(raw, window.location.href);
      if (url.origin !== window.location.origin) return;
      if (lang === 'ar') url.searchParams.delete('lang');
      else url.searchParams.set('lang', lang);
      link.setAttribute('href', url.pathname.split('/').pop() + url.search + url.hash);
    } catch (_) {}
  });
}

window.setLang = setLang;
window.translations = translations;

let languageObserver;
let languageTimer;
function applyCurrentLanguage() {
  const fromUrl = new URLSearchParams(window.location.search).get('lang');
  const saved = ['ar','en','es'].includes(fromUrl) ? fromUrl : (localStorage.getItem('basma_lang') || 'ar');
  if (languageObserver) languageObserver.disconnect();
  setLang(saved);
  if (languageObserver) languageObserver.observe(document.body, { childList:true, subtree:true });
}

document.addEventListener('DOMContentLoaded', function () {
  languageObserver = new MutationObserver(function(mutations) {
    if (!mutations.some(function(m){ return m.addedNodes && m.addedNodes.length; })) return;
    clearTimeout(languageTimer);
    languageTimer = setTimeout(applyCurrentLanguage, 0);
  });
  applyCurrentLanguage();
  setTimeout(applyCurrentLanguage, 80);
  setTimeout(applyCurrentLanguage, 350);
});

document.addEventListener('click', function (e) {
  const el = e.target.closest('[data-lang-switch]');
  if (!el) return;
  e.preventDefault();
  setLang(el.getAttribute('data-lang-switch'));
  const details = el.closest('details');
  if (details) details.open = false;
});
